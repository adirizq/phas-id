import argparse
import json
import os
import time

import pandas as pd
import requests
from dotenv import load_dotenv
from sklearn.metrics import classification_report
from tqdm import tqdm

from src.phas_id.data_module import PHASIDDataModule

load_dotenv()

INT_TO_STR = {0: "Human", 1: "AI", 2: "AI-Human"}
STR_TO_INT = {"Human": 0, "AI": 1, "AI-Human": 2, "human": 0, "ai": 1, "ai-human": 2}

OPENROUTER_BASE = "https://openrouter.ai/api/v1/chat/completions"

LABEL_SCHEMA = {
    "type": "json_schema",
    "json_schema": {
        "name": "sentence_labels",
        "strict": True,
        "schema": {
            "type": "object",
            "properties": {
                "labels": {
                    "type": "array",
                    "items": {
                        "type": "string",
                        "enum": ["Human", "AI", "AI-Human"],
                    },
                }
            },
            "required": ["labels"],
            "additionalProperties": False,
        },
    },
}


# Prompt builders
SYSTEM_PROMPT = "You are an expert text classifier. Your task is to determine, for each sentence in a document, whether it was written purely by an AI, purely by a Human, or through Human-AI collaboration."

LABEL_INSTRUCTIONS = """\
* Use "AI" if the sentence appears entirely generated by an AI.
* Use "Human" if the sentence appears entirely written by a human.
* Use "AI-Human" if the sentence shows characteristics of both AI generation \
and human writing/editing (e.g., AI text modified by a human, human text with \
AI-generated parts, or a blend of styles).\
"""


def build_support_block(support_sentences: list[list[str]], support_labels: list[list[int]]) -> str:
    if not support_sentences:
        return ""

    lines = ["## Author Writing Style Reference\nThe following documents were written by the same author as the target document. Each sentence is labelled with its true class. Use these examples to calibrate your understanding of this author's writing style before classifying the target.\n"]

    for doc_idx, (sents, labels) in enumerate(zip(support_sentences, support_labels), 1):
        lines.append(f"### Reference Document {doc_idx}")
        for sent, lbl in zip(sents, labels):
            label_str = INT_TO_STR.get(lbl, "Human")
            lines.append(f"[{label_str}] {sent}")
        lines.append("")  # blank line between documents

    return "\n".join(lines)


def build_prompt(
    target_sentences: list[str],
    support_sentences: list[list[str]],
    support_labels: list[list[int]],
) -> str:
    n = len(target_sentences)

    support_block = build_support_block(support_sentences, support_labels)

    target_block_lines = ["## Target Document to Classify\nClassify each numbered sentence below. Consider the author's writing style shown above."]
    for i, sent in enumerate(target_sentences, 1):
        target_block_lines.append(f"{i}. {sent}")

    output_instruction = f'\n## Output Format\nRespond with a JSON object with a single key "labels" containing an array of exactly {n} strings.\nEach element must be exactly one of: "Human", "AI", or "AI-Human".\nThe array must contain exactly {n} elements, one per sentence, in the same order.\nExample: {{"labels": ["Human", "AI", "AI-Human"]}}'

    parts = [
        LABEL_INSTRUCTIONS,
        "",
        support_block,
        "\n".join(target_block_lines),
        output_instruction,
    ]

    return "\n".join(parts)


# OpenRouter API call
def call_llm(
    prompt: str,
    llm: str,
    api_key: str,
    temperature: float = 0.0,
    max_retries: int = 5,
    retry_delay: float = 10.0,
) -> str | None:
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
    }
    payload = {
        "model": llm,
        "temperature": temperature,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": prompt},
        ],
        "response_format": LABEL_SCHEMA,
    }

    for attempt in range(1, max_retries + 1):
        try:
            resp = requests.post(OPENROUTER_BASE, headers=headers, json=payload, timeout=120)
            resp.raise_for_status()
            data = resp.json()
            return data["choices"][0]["message"]["content"].strip()
        except requests.exceptions.HTTPError as e:
            status = e.response.status_code if e.response is not None else "?"
            print(f"  [HTTP {status}] attempt {attempt}/{max_retries}: {e}")
            if status == 429 or status == "?" or (isinstance(status, int) and status >= 500):
                time.sleep(retry_delay * attempt)
            else:
                return None
        except Exception as e:
            print(f"  [Error] attempt {attempt}/{max_retries}: {e}")
            time.sleep(retry_delay)

    return None


# Response parser
def parse_response(response: str | None, n_sentences: int) -> list[int]:
    if response is None:
        print("  [Warning] None response, defaulting all to Human (0)")
        return [0] * n_sentences

    # Primary: structured JSON output
    try:
        data = json.loads(response)
        raw_labels = data.get("labels", [])
        labels = []
        for item in raw_labels:
            label_int = STR_TO_INT.get(item, STR_TO_INT.get(item.capitalize(), None))
            if label_int is None:
                lower = item.lower()
                if "ai-human" in lower or "human-ai" in lower:
                    label_int = 2
                elif "ai" in lower:
                    label_int = 1
                else:
                    label_int = 0
            labels.append(label_int)

        if len(labels) != n_sentences:
            print(f"  [Parse mismatch] expected {n_sentences} labels, got {len(labels)}")
            if len(labels) < n_sentences:
                labels += [0] * (n_sentences - len(labels))
            else:
                labels = labels[:n_sentences]
        return labels
    except (json.JSONDecodeError, AttributeError):
        print("  [Warning] JSON parse failed, falling back to line-by-line parsing")

    # Fallback: line-by-line text parsing
    raw_lines = [lbl.strip() for lbl in response.splitlines() if lbl.strip()]
    cleaned = []
    for line in raw_lines:
        if ". " in line[:4]:
            line = line.split(". ", 1)[-1].strip()
        cleaned.append(line)

    labels = []
    for line in cleaned:
        label_int = STR_TO_INT.get(line, STR_TO_INT.get(line.capitalize(), None))
        if label_int is None:
            lower = line.lower()
            if "ai-human" in lower or "human-ai" in lower:
                label_int = 2
            elif "ai" in lower:
                label_int = 1
            elif "human" in lower:
                label_int = 0
            else:
                label_int = 0
        labels.append(label_int)

    if len(labels) != n_sentences:
        print(f"  [Parse mismatch] expected {n_sentences} labels, got {len(labels)}")
        if len(labels) < n_sentences:
            labels += [0] * (n_sentences - len(labels))
        else:
            labels = labels[:n_sentences]

    return labels


# Metric calculation
def calculate_metrics(targets: list[int], predictions: list[int], num_classes: int = 3) -> dict:
    class_labels = ["Human", "AI", "AI-Human"][:num_classes]
    labels = list(range(num_classes))
    report: dict = classification_report(
        targets,
        predictions,
        labels=labels,
        target_names=class_labels,
        output_dict=True,
        zero_division=0,  # type: ignore
    )  # type: ignore

    per_class = {}
    for i, name in enumerate(class_labels):
        if name in report:
            per_class[i] = {
                "f1": report[name]["f1-score"] * 100,
                "precision": report[name]["precision"] * 100,
                "recall": report[name]["recall"] * 100,
            }
        else:
            per_class[i] = {"f1": 0.0, "precision": 0.0, "recall": 0.0}

    return {
        "accuracy": report["accuracy"] * 100,
        "macro_f1": report["macro avg"]["f1-score"] * 100,
        "weighted_f1": report["weighted avg"]["f1-score"] * 100,
        "per_class": per_class,
    }


def main():
    parser = argparse.ArgumentParser(description="LLM Personalized Baseline for sentence-level AIGT detection")
    parser.add_argument("-ra_p", "--raw_data_path", type=str, default="dataset/coauthor/raw.csv")
    parser.add_argument("-pa_p", "--parsed_data_path", type=str, default="dataset/coauthor/parsed_phas_id.jsonl")
    parser.add_argument("--model_name", type=str, default="microsoft/deberta-v3-base")
    parser.add_argument("--dataset", type=str, default="coauthor", choices=["coauthor", "hacodet"])
    parser.add_argument("--llm", type=str, default="openai/gpt-4o", help="OpenRouter model identifier")
    parser.add_argument("--K", type=int, default=5, help="Number of support documents per episode")
    parser.add_argument("--token_limit", type=int, default=128)
    parser.add_argument("--output_path", type=str, default="logs/llm_personalized_baseline")
    parser.add_argument("--recreate", action="store_true")
    parser.add_argument("--max_retries", type=int, default=5)
    parser.add_argument("--retry_delay", type=float, default=10.0)
    parser.add_argument("--retry_temperature", type=float, default=0.3)
    parser.add_argument("--max_length_retries", type=int, default=3)
    parser.add_argument("--max_episodes", type=int, default=None, help="Limit number of test episodes (for quick testing)")
    args = parser.parse_args()

    num_classes = 3 if args.dataset == "coauthor" else 2
    api_key = os.getenv("OPENROUTER_API_KEY")

    if api_key is None:
        print("Error: OPENROUTER_API_KEY environment variable not set")
        return

    os.makedirs(args.output_path, exist_ok=True)

    print("Initializing datamodule...")
    datamodule = PHASIDDataModule(
        raw_data_path=args.raw_data_path,
        parsed_data_path=args.parsed_data_path,
        model_name=args.model_name,
        token_limit=args.token_limit,
        K=args.K,
        num_classes=num_classes,
        recreate=args.recreate,
    )
    datamodule.setup(stage="test")
    test_loader = datamodule.test_dataloader()

    print(f"Test episodes: {len(datamodule.test_dataset)}")
    print(f"LLM: {args.llm}")

    # Inference loop
    all_targets = []
    all_predictions = []
    all_ids = []
    all_fallbacks = []
    failed_episodes = []

    for batch_idx, batch in enumerate(tqdm(test_loader, desc="Inference")):
        if args.max_episodes is not None and batch_idx >= args.max_episodes:
            break
        session_id = batch["session_id"]
        sent_ids = batch["sent_ids"]
        target_labels = batch["target_labels"].tolist()
        target_sentences = batch["target_sentences"]  # List[str]  (added in dataset patch)
        support_sentences = batch["support_sentences"]  # List[List[str]]
        support_raw_labels = batch["support_raw_labels"]  # List[List[int]]

        n = len(target_sentences)

        prompt = build_prompt(target_sentences, support_sentences, support_raw_labels)

        response = call_llm(
            prompt,
            args.llm,
            api_key,
            temperature=0.0,
            max_retries=args.max_retries,
            retry_delay=args.retry_delay,
        )

        # Retry with a non-zero temperature when the label count doesn't match
        for length_attempt in range(args.max_length_retries):
            if response is None:
                break
            try:
                n_predicted = len(json.loads(response).get("labels", []))
            except (json.JSONDecodeError, AttributeError):
                break  # unparseable — let parse_response handle it
            if n_predicted == n:
                break
            print(f"  [Episode {batch_idx}] label count mismatch (expected {n}, got {n_predicted}), retrying at temperature={args.retry_temperature} (attempt {length_attempt + 1}/{args.max_length_retries})")
            response = call_llm(
                prompt,
                args.llm,
                api_key,
                temperature=args.retry_temperature,
                max_retries=args.max_retries,
                retry_delay=args.retry_delay,
            )

        if response is None:
            print(f"  [Episode {batch_idx}] API failure, defaulting to Human")
            failed_episodes.append(session_id)

        # Detect whether parse_response will need to pad/truncate
        used_fallback = False
        if response is None:
            used_fallback = True
        else:
            try:
                n_predicted = len(json.loads(response).get("labels", []))
                used_fallback = n_predicted != n
            except (json.JSONDecodeError, AttributeError):
                used_fallback = True

        predictions = parse_response(response, n)

        all_targets.extend(target_labels)
        all_predictions.extend(predictions)
        all_ids.extend([f"{session_id}_{i}" for i in sent_ids])
        all_fallbacks.extend([used_fallback] * n)

    # Metrics
    metrics = calculate_metrics(all_targets, all_predictions, num_classes)

    class_names = ["Human", "AI", "AI-Human"][:num_classes]
    print("\n" + "=" * 60)
    print(f"LLM Personalized Baseline — {args.llm}")
    print("=" * 60)
    print(f"Macro F1:    {metrics['macro_f1']:.2f}")
    print(f"Accuracy:    {metrics['accuracy']:.2f}")
    for i, name in enumerate(class_names):
        pc = metrics["per_class"][i]
        print(f"  {name:<12} P={pc['precision']:.2f}  R={pc['recall']:.2f}  F1={pc['f1']:.2f}")
    if failed_episodes:
        print(f"\nFailed episodes (API errors): {len(failed_episodes)}")
    print("=" * 60)

    # Save outputs
    llm_slug = args.llm.replace("/", "_")

    df = pd.DataFrame(
        {
            "id": all_ids,
            "target": all_targets,
            "prediction": all_predictions,
            "fallback": all_fallbacks,
        }
    )
    pred_path = os.path.join(args.output_path, f"{llm_slug}_predictions.csv")
    df.to_csv(pred_path, index=False)
    print(f"Predictions saved to: {pred_path}")

    metrics_path = os.path.join(args.output_path, f"{llm_slug}_metrics.json")
    with open(metrics_path, "w") as f:
        json.dump(
            {
                "llm": args.llm,
                "K": args.K,
                "dataset": args.dataset,
                "failed_episodes": failed_episodes,
                **metrics,
            },
            f,
            indent=4,
        )
    print(f"Metrics saved to:      {metrics_path}")


if __name__ == "__main__":
    main()
